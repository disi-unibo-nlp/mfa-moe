"""Export the measured routing-intervention results into the journal manuscript.

Reads the sealed effects receipts of the reduced final-routing study (no fitting or
resampling here) and writes:
  manuscript-support/figures/data/routing.dat           coordinates of the routing figure
  manuscript-support/figures/data/routing_results.json  every displayed number and its source receipt
  journal/tables/routing.tex                 main paired contrasts (8 models and the pooled row)
  journal/tables/routing_levels.tex          per-arm accuracy and token levels (appendix)
  journal/tables/routing_strong.tex          exploratory strong-dose arm (appendix)

Intervals are the receipts' max-|t| simultaneous 95% envelopes: within each model over its
four primary contrasts, its efficiency contrasts or its arm levels. Token ratios are shown
as percent changes; their symmetric display uses the larger one-sided margin.
"""
from pathlib import Path
import hashlib
import json
import math

from cl_paths import DATA, FIGURES, PAPER, REPO  # noqa: E402

TABLES = PAPER / "journal/tables"
DRIVER = REPO / "report/final-routing-20261015-r1/driver"
MAIN = DRIVER / "analysis-final/EFFECTS.json"
STRONG = DRIVER / "analysis-strong/EFFECTS.json"
MODELS = ("gpt", "nemotron", "qwen35", "qwen36", "gemma", "glm", "qwen330b", "lfm25")
TABLE_NAMES = {
    "gpt": r"\modelname{openai}{GPT-OSS-20B}",
    "nemotron": r"\modelname{nvidia}{Nemotron-3.5-Lightning-30B-A3B}",
    "qwen35": r"\modelname{qwen}{Qwen3.5-35B-A3B}",
    "qwen36": r"\modelname{qwen}{Qwen3.6-35B-A3B}",
    "gemma": r"\modelname{gemma}{Gemma-4-26B-A4B}",
    "glm": r"\modelname{zhipu}{GLM-4.7-Flash (30B-A3B)}",
    "qwen330b": r"\modelname{qwen}{Qwen3-30B-A3B}",
    "lfm25": r"\modelname{liquid}{LFM2.5-24B-A2B}",
}
LONG_NAMES = TABLE_NAMES
ARMS = (("native", "Native"), ("target_activate", "Targeted activation"), ("random_activate", "Random activation"),
        ("target_deactivate", "Targeted deactivation"), ("random_deactivate", "Random deactivation"))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verified(path):
    value = json.loads(path.read_text())
    seal = value.pop("sha256")
    payload = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False)
    if hashlib.sha256(payload.encode()).hexdigest() != seal:
        raise ValueError("effects receipt seal differs: " + str(path))
    return {**value, "sha256": seal}


def points(v, scale=100.):
    """Mean and symmetric margin (larger one-sided distance to the simultaneous limits), in display units."""
    mean = scale * v["estimate"]
    low, high = (scale * x for x in v["simultaneous"])
    return mean, max(mean - low, high - mean)


def percent(v):
    """Percent change of a mean log ratio and its symmetric margin on the percent scale."""
    mean = 100 * math.expm1(v["estimate"])
    low, high = (100 * math.expm1(x) for x in v["simultaneous"])
    return mean, max(mean - low, high - mean)


def cid(mean, margin, digits):
    return "\\cid{" + f"{mean:.{digits}f}" + "}{" + f"{margin:.{digits}f}" + "}{" + f"{margin:.{digits}f}" + "}"


TICKS = ("{\\plotmodel{openai}{}{20B}},{\\plotmodel{nvidia}{3.5}{30B}},{\\plotmodel{qwen}{3.5}{35B}},"
         "{\\plotmodel{qwen}{3.6}{35B}},{\\plotmodel{gemma}{4}{26B}},{\\plotmodel{zhipu}{4.7}{30B}},"
         "{\\plotmodel{qwen}{3}{30B}},{\\plotmodel{liquid}{2.5}{24B}},{\\shortstack{All\\\\models}}")
COLORS = ("gomblueone", "gombluetwo", "gomorangeone", "gomorangetwo")
SHIFTS = (-10.5, -3.5, 3.5, 10.5)


def figure(coords, panels):
    """Native GoM signed grouped bars, three stacked metric panels; value labels sit beyond each whisker."""
    out = ["% Native GoM signed grouped-bar recipe (plot-gom-signed-bars.tex) in stacked MoM-style panels.",
           "% Generated by scripts/paper/export_routing_results.py from figures/journal/data/routing.dat.",
           "\\begin{tikzpicture}"]
    height, gap = 62, 30
    for p, (title, columns, limits, ticks, digits) in enumerate(panels):
        y = (len(panels) - 1 - p) * (height + gap)
        last = p == len(panels) - 1
        out.append("\\begin{axis}[journalaxis,scale only axis,width=352pt,height=" + str(height) + "pt,anchor=south west,"
                   "at={(0pt," + str(y) + "pt)},ybar=0pt,bar width=6pt,xmin=.5,xmax=9.5,enlarge x limits=false,"
                   "ymin=" + str(limits[0]) + ",ymax=" + str(limits[1]) + ",ytick={" + ticks + "},"
                   "xtick={1,2,3,4,5,6,7,8,9},xticklabels={" + TICKS + "},"
                   "xticklabel style={rotate=0,anchor=north,align=center,font=\\fontsize{7}{8}\\selectfont},"
                   + ("" if last else "xticklabels=\\empty,") +
                   "extra y ticks={0},extra y tick style={grid=major,major grid style={draw=gomaxis,line width=.45pt}},"
                   "title={\\textbf{" + title + "}},title style={font=\\fontsize{8}{9}\\selectfont}]")
        for k, column in enumerate(columns):
            out.append("\\addplot[fill=" + COLORS[k] + ",draw=black,line width=.35pt,bar shift=" + str(SHIFTS[k])
                       + "pt,journalerror] table[x=x,y=" + column + ",y error=" + column + "_pm]"
                       "{figures/journal/data/routing.dat};")
            index = 1 + 2 * HEADINGS.index(column)
            for row in coords:
                mean, margin = row[index], row[index + 1]
                end = mean + margin if mean >= 0 else mean - margin
                anchor = "west" if mean >= 0 else "east"
                out.append("\\node[rotate=90,anchor=" + anchor + ",inner sep=1pt,font=\\fontsize{5.6}{6}\\selectfont] at "
                           "([xshift=" + str(SHIFTS[k]) + "pt]axis cs:" + str(row[0]) + "," + format(end, ".4g") + ") {"
                           + "$" + f"{mean:.{digits}f}" + "$};")
        out.append("\\end{axis}")
    out.append("\\node[journallegend,anchor=north,yshift=-4pt,font=\\fontsize{7.5}{9}\\selectfont] at (176pt,0pt |- current bounding box.south) {"
               "\\begin{tabular}{@{}l@{\\enspace}l@{\\quad}l@{\\quad}l@{\\quad}l@{}}"
               "(a) & \\statekey{gomblueone}{Occupancy, act.} & \\statekey{gombluetwo}{First sentence, act.} & "
               "\\statekey{gomorangeone}{Occupancy, deact.} & \\statekey{gomorangetwo}{First sentence, deact.}\\\\"
               "(b, c) & \\statekey{gomblueone}{Targeted act.} & \\statekey{gombluetwo}{Random act.} & "
               "\\statekey{gomorangeone}{Targeted deact.} & \\statekey{gomorangetwo}{Random deact.}\\end{tabular}};")
    out.append("\\end{tikzpicture}")
    (FIGURES / "routing.tex").write_text("\n".join(out) + "\n")


HEADINGS = []


def main():
    effects, strong = verified(MAIN), verified(STRONG)
    if tuple(effects["models"]) != MODELS or effects["design"] != "main":
        raise ValueError("main effects roster differs")
    groups = [(m, effects["primary_by_model"][m], effects["efficiency_by_model"][m]) for m in MODELS]
    groups.append(("all", effects["primary_pooled"], effects["efficiency_pooled"]))
    state = ("activate:occupancy", "deactivate:occupancy", "activate:first", "deactivate:first")
    accuracy = ("activate:correct:vs_native", "random_activate:correct:vs_native",
                "deactivate:correct:vs_native", "random_deactivate:correct:vs_native")
    tokens = ("activate:log_tokens:vs_native", "random_activate:log_tokens:vs_native",
              "deactivate:log_tokens:vs_native", "random_deactivate:log_tokens:vs_native")
    record, coords, rows = {}, [], []
    for i, (model, primary, efficiency) in enumerate(groups, 1):
        cells = {k: points(primary[k]) for k in state}
        cells.update({k: points(efficiency[k]) for k in accuracy + ("activate:correct",)})
        cells.update({k: percent(efficiency[k]) for k in tokens + ("activate:log_tokens",)})
        record[model] = {k: {"mean": m, "margin": e} for k, (m, e) in cells.items()}
        coords.append((i, *[x for k in state + accuracy + tokens for x in cells[k]]))
        name = TABLE_NAMES.get(model, "All models")
        values = [cid(*cells[k], 2) for k in state] + [cid(*cells["activate:correct"], 2), cid(*cells["activate:log_tokens"], 1),
                  cid(*cells["activate:correct:vs_native"], 2), cid(*cells["activate:log_tokens:vs_native"], 1)]
        rows.append(("\\midrule\n" if model == "all" else "") + name + " & " + " & ".join(values) + " \\\\")
    HEADINGS[:] = [k.replace(':', '_') for k in state + accuracy + tokens]
    heading = " ".join(f"{k} {k}_pm" for k in HEADINGS)
    (DATA / "routing.dat").write_text("x " + heading + "\n" + "\n".join(
        " ".join(format(v, ".6g") for v in row) for row in coords) + "\n")
    name = lambda keys: [k.replace(':', '_') for k in keys]
    figure(coords, [("(a) Target-state effect, targeted $-$ matched random (pp)", name(
                         ("activate:occupancy", "activate:first", "deactivate:occupancy", "deactivate:first")),
                     (-6.5, 6), "-6,-4,-2,0,2,4,6", 2),
                    ("(b) Accuracy change from native routing (pp)", name(accuracy), (-17, 10), "-15,-10,-5,0,5", 1),
                    ("(c) Generated-token change from native routing (\\%)", name(tokens), (-42, 33), "-30,-15,0,15,30", 1)])

    table = r"""% Source: report/final-routing-20261015-r1/driver/analysis-final/EFFECTS.json via scripts/paper/export_routing_results.py.
\begin{table}[tb]
\centering\small
\caption{Paired effects of routing interventions at central strength, with family-bootstrap simultaneous 95\% confidence intervals as subscripts.
%
State columns give targeted minus matched-random arms in percentage points for target-state occupancy over the analysis window and for the first complete sentence; positive values favor the intended direction of activation or deactivation.
%
Efficiency columns compare targeted activation with matched random activation and with native routing, as accuracy in percentage points and generated tokens to the final answer in percent.
%
Each model uses its prepared family prefixes, 129 families except Nemotron and Qwen3-30B (128) and LFM2.5 (112).
%
Intervals are simultaneous over the four state contrasts or over all efficiency contrasts of the row.}
\label{tab:routing}
\setlength{\tabcolsep}{2.5pt}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}lcccccccc@{}}
\toprule
 & \multicolumn{4}{c}{Target state, targeted $-$ random (pp)} & \multicolumn{2}{c}{Activation $-$ random} & \multicolumn{2}{c}{Activation $-$ native} \\
\cmidrule(lr){2-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}
Model & Occ.\ act. & Occ.\ deact. & First act. & First deact. & Acc.\ (pp) & Tokens (\%) & Acc.\ (pp) & Tokens (\%) \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}
\end{table}
"""
    (TABLES / "routing.tex").write_text(table)

    levels = []
    for model in MODELS:
        level = effects["levels_by_model"][model]
        levels.append("\\multicolumn{5}{l}{" + LONG_NAMES[model] + "}\\\\*")
        record[model]["levels"] = {}
        for j, (arm, label) in enumerate(ARMS):
            acc, gen, rea, stop = (points(level[arm + ":correct"]), points(level[arm + ":generated_tokens"], 1.),
                                   points(level[arm + ":reasoning_tokens"], 1.), points(level[arm + ":stopped"]))
            record[model]["levels"][arm] = {"accuracy": acc, "generated_tokens": gen, "reasoning_tokens": rea,
                                            "natural_stop": stop, "cells": level[arm + ":correct"]["cells"]}
            end = " \\\\*" if j < len(ARMS) - 1 else " \\\\"
            levels.append(label + " & " + cid(*acc, 2) + " & " + cid(*gen, 0) + " & " + cid(*rea, 0) + " & "
                          + cid(*stop, 1) + end)
        if model != MODELS[-1]:
            levels.append("\\midrule")
    header = r"Arm & Accuracy (\%) & Generated tokens & Reasoning tokens & Natural end (\%) \\"
    (TABLES / "routing_levels.tex").write_text(r"""% Multipage longtable: retained outside adjustbox so page breaks remain available.
% Source: analysis-final/EFFECTS.json levels_by_model via scripts/paper/export_routing_results.py.
\begingroup\small
\setlength{\tabcolsep}{2pt}
\begin{longtable}{lcccc}
\caption{Accuracy and token levels of every intervention arm, with family-bootstrap simultaneous 95\% confidence intervals as subscripts.
%
Accuracy is strict answer scoring of the completed continuation.
%
Generated tokens follow the frozen prefix, and reasoning tokens are the generated tokens before the reasoning closes.
%
Random arms use the matched control sets, and natural end is the share of continuations that stop before their original generation allowance.
%
Benchmarks and supported families receive equal weight, and intervals are simultaneous over the arm and metric cells of each model.}\label{tab:routing-levels}\\
\toprule
""" + header + r"""
\midrule\endfirsthead
\multicolumn{5}{l}{\textit{Continued}}\\
\toprule
""" + header + r"""
\midrule\endhead
\bottomrule\endfoot
""" + "\n".join(levels) + r"""
\end{longtable}
\endgroup
""")

    if tuple(strong["models"]) != ("gpt", "nemotron", "qwen330b", "gemma") or strong["design"] != "strong":
        raise ValueError("strong-dose roster differs")
    srows, record["strong"] = [], {}
    for model in strong["models"] + ["all"]:
        primary = strong["primary_pooled"] if model == "all" else strong["primary_by_model"][model]
        cells = [points(primary["activate:occupancy"]), points(primary["activate:first"])]
        record["strong"][model] = {"occupancy": cells[0], "first": cells[1]}
        if model == "all":
            e = strong["efficiency_pooled"]
            cells += [points(e["activate:correct"]), percent(e["activate:log_tokens"]),
                      points(e["activate:correct:vs_native"]), points(e["random_activate:correct:vs_native"])]
            record["strong"][model].update(accuracy_vs_random=cells[2], tokens_vs_random=cells[3],
                                           accuracy_vs_native=cells[4], random_accuracy_vs_native=cells[5])
            values = [cid(*cells[0], 2), cid(*cells[1], 2), cid(*cells[2], 2), cid(*cells[3], 1), cid(*cells[4], 2),
                      cid(*cells[5], 2)]
            srows.append("\\midrule\nAll four models & " + " & ".join(values) + " \\\\")
        else:
            srows.append(TABLE_NAMES[model] + " & " + cid(*cells[0], 2) + " & " + cid(*cells[1], 2)
                         + " & \\textemdash & \\textemdash & \\textemdash & \\textemdash \\\\")
    (TABLES / "routing_strong.tex").write_text(r"""% Source: report/final-routing-20261015-r1/driver/analysis-strong/EFFECTS.json via scripts/paper/export_routing_results.py.
\begin{table}[tb]
\centering\small
\caption{Exploratory strong-dose activation, with family-bootstrap simultaneous 95\% confidence intervals as subscripts.
%
The arm forces the nominated high-count expert sets at all three depth regions throughout the analysis window and compares them with the matched high-count control sets.
%
State columns give targeted minus matched-random percentage points.
%
Accuracy is in percentage points and generated tokens in percent; efficiency contrasts are estimated on the pooled population only.}
\label{tab:routing-strong}
\setlength{\tabcolsep}{2.5pt}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}lcccccc@{}}
\toprule
 & \multicolumn{2}{c}{Target state (pp)} & \multicolumn{2}{c}{Targeted $-$ random} & \multicolumn{2}{c}{Accuracy $-$ native (pp)} \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}
Model & Occupancy & First & Acc.\ (pp) & Tokens (\%) & Targeted & Random \\
\midrule
""" + "\n".join(srows) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}
\end{table}
""")

    prereg = verified(DRIVER / "EFFICIENCY_LINK_PREREG.json")
    if effects["efficiency_link"]["prereg_sha256"] != prereg["sha256"]:
        raise ValueError("efficiency-link test used a different pre-registration")
    order = ("Read", "Analyze", "Explore", "Plan", "Implement", "Verify", "Monitor")
    cells = {(c["model"], c["class"]): c["tok_reason"] for c in prereg["cells"]}
    pooled_link = {c["class"]: c["tok_reason"] for c in prereg["pooled"]}
    link_rows = []
    for model in prereg["models"] + ["pooled"]:
        entries = []
        for c in order:
            v = pooled_link[c] if model == "pooled" else cells[model, c]
            mean, low, high = (100 * v[k] for k in ("beta", "ci_low", "ci_high"))
            entries.append(cid(mean, mean - low, 2).replace("}{" + f"{mean - low:.2f}" + "}{" + f"{mean - low:.2f}" + "}",
                           "}{" + f"{mean - low:.2f}" + "}{" + f"{high - mean:.2f}" + "}"))
        name = "Seven-model mean" if model == "pooled" else TABLE_NAMES[model]
        link_rows.append(("\\midrule\n" if model == "pooled" else "") + name + " & " + " & ".join(entries) + " \\\\")
    (TABLES / "efficiency_link.tex").write_text(r"""% Source: report/final-routing-20261015-r1/driver/EFFICIENCY_LINK_PREREG.json via scripts/paper/export_routing_results.py.
\begin{table}[tb]
\centering\small
\caption{Pre-registered native association between the current reasoning state and the remaining reasoning length, with 95\% family-bootstrap confidence intervals as subscripts.
%
Entries are 100 times the regression coefficient of a class indicator on the log of the reasoning tokens that remain after the sentence, with question and absolute-position fixed effects.
%
Negative values mark states followed by shorter remaining reasoning.
%
The coefficients were frozen before any intervention outcome existed.}
\label{tab:efficiency-link}
\setlength{\tabcolsep}{2pt}
\begin{adjustbox}{max width=\linewidth}
\begin{tabular}{@{}lccccccc@{}}
\toprule
Model & \textrm{Re} & \textrm{An} & \textrm{Ex} & \textrm{Pl} & \textrm{Im} & \textrm{Ve} & \textrm{Mo} \\
\midrule
""" + "\n".join(link_rows) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}
\end{table}
""")

    pooled = effects["efficiency_pooled"]
    record["pooled_secondary"] = {k: {"estimate": v["estimate"], "simultaneous": v["simultaneous"], "ci": v["ci"]}
                                  for k, v in {**pooled, **effects["secondary_pooled"]}.items()}
    record["efficiency_link"] = {k: effects["efficiency_link"][k] for k in ("tokens", "accuracy")}
    record["rogan_gladen"] = effects["rogan_gladen_sensitivity"]
    record["response_matrix"] = effects["response_matrix"]
    record["counts"] = {"continuations": effects["continuations"], "pairs": effects["pairs"],
                        "strong_continuations": strong["continuations"], "strong_pairs": strong["pairs"]}
    record["sources"] = {str(p.relative_to(REPO)): {"file_sha256": sha(p), "receipt_sha256": verified(p)["sha256"]}
                         for p in (MAIN, STRONG)}
    (DATA / "routing_results.json").write_text(json.dumps(record, indent=1, default=float) + "\n")
    print(json.dumps({"models": len(MODELS), "continuations": effects["continuations"], "pairs": effects["pairs"],
                      "strong_models": len(strong["models"]), "tables": 3}))


if __name__ == "__main__":
    main()
