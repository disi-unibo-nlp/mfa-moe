"""Render the completed CPU grouped-probe study without rerunning inference."""

from __future__ import annotations

import hashlib
import json
from collections import Counter
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "report"
MODELS = [
    ("Qwen", "qwen3.5-35b-a3b-gptq-int4"),
    ("GPT-OSS", "gpt-oss-20b"),
    ("Gemma", "gemma-4-26b-a4b-it-nf4"),
]
TARGETS = ("Read", "Analyze", "Plan", "Implement", "Explore", "Verify", "Monitor")


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def interval(value, signed=False):
    point = format(value["estimate"], "+.3f" if signed else ".3f")
    lo, hi = value["ci95"]
    return f"${point}$ [{lo:.3f}, {hi:.3f}]"


def table(path, caption, label, columns, header, rows):
    text = (
        "% Generated by report/generate_grouped_probe_results.py\n"
        "\\begin{table*}[tbp]\n\\centering\\small\n"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
        "\\resizebox{\\textwidth}{!}{%\n"
        f"\\begin{{tabular}}{{{columns}}}\n\\toprule\n"
        + header
        + " \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}}\n\\end{table*}\n"
    )
    path.write_text(text)


def main():
    hashes = {str(Path(__file__).relative_to(ROOT)): digest(Path(__file__))}
    runs, audit, plan_hashes = {}, {}, set()
    macro_rows, target_rows = [], []
    for name, slug in MODELS:
        directory = ROOT / "results/probeTest" / slug / "probes_grouped_s42"
        paths = [
            directory / f
            for f in (
                "results.json",
                "run_config.json",
                "split_plan.json",
                "predictions.jsonl",
                "unit_index.jsonl",
            )
        ]
        legacy_path = directory.parent / "probes/results.json"
        for path in paths + [legacy_path]:
            hashes[str(path.relative_to(ROOT))] = digest(path)
        result = json.loads(paths[0].read_text())
        plan = json.loads(paths[2].read_text())
        config = result["config"]
        assert result["status"] == "complete" and config["protocol"] == "grouped"
        assert config["n_samples"] == 3087 and config["n_responses"] == 38
        assert config["outer_folds"] == 5 and len(result["folds"]) == 35
        plan_hash = hashlib.sha256(json.dumps(plan, sort_keys=True).encode()).hexdigest()
        assert plan_hash == config["split_plan_sha256"]
        plan_hashes.add(plan_hash)
        assert config == json.loads(paths[1].read_text())
        for filename, expected in config["code_sha256"].items():
            path = ROOT / "src/moe_exp/probeTest" / filename
            assert digest(path) == expected, f"Code changed since fitting: {filename}"
            hashes[str(path.relative_to(ROOT))] = expected
        units = [json.loads(line) for line in paths[4].read_text().splitlines()]
        predictions = [json.loads(line) for line in paths[3].read_text().splitlines()]
        counts = Counter((r["sample_index"], r["target"]) for r in predictions)
        assert len(counts) == 3087 * 7 and set(counts.values()) == {1}
        for fold in plan["folds"]:
            fit, val, test = [set(fold[k + "_responses"]) for k in ("fit", "validation", "test")]
            assert not (fit & val or fit & test or val & test)
        for row in predictions:
            assert row["response_id"] in plan["folds"][row["fold"]]["test_responses"]
            assert row["y"] == int(units[row["sample_index"]]["label"] == row["target"])
        for fold in result["folds"]:
            chosen = max(
                fold["validation_candidates"], key=lambda r: (r["validation_auc"], -r["layer_idx"])
            )
            assert chosen["layer_idx"] == fold["selected_layer"]
            for method in ("probe", "position"):
                for metric in ("auc", "balanced_accuracy", "f1", "accuracy"):
                    value = np.mean(
                        [
                            r["metrics"][method][metric]
                            for r in result["folds"]
                            if r["target"] == fold["target"]
                        ]
                    )
                    assert np.isclose(
                        value,
                        result["summary"]["targets"][fold["target"]][method][metric]["estimate"],
                    )
        legacy = json.loads(legacy_path.read_text())
        legacy_auc = np.mean([legacy["best_by_target"][t]["test_auc"] for t in TARGETS])
        summary = result["summary"]
        macro = summary["macro"]
        macro_rows.append(
            " & ".join(
                [
                    name,
                    f"{legacy_auc:.3f}",
                    interval(macro["probe"]["auc"]),
                    interval(macro["position"]["auc"]),
                    interval(macro["probe_minus_position"]["auc"], True),
                ]
            )
            + r" \\"
        )
        if target_rows:
            target_rows.append(r"\midrule")
        for target in TARGETS:
            values = summary["targets"][target]
            selected = [r["selected_layer"] for r in result["folds"] if r["target"] == target]
            target_rows.append(
                " & ".join(
                    [
                        name,
                        target,
                        interval(values["probe"]["auc"]),
                        interval(values["probe_minus_position"]["auc"], True),
                        f"{values['probe']['balanced_accuracy']['estimate']:.3f}",
                        f"{values['probe']['f1']['estimate']:.3f}",
                        ", ".join(map(str, selected)),
                    ]
                )
                + r" \\"
            )
        candidates = [c for r in result["folds"] for c in r["validation_candidates"]]
        warnings = {
            "inner": sum(bool(c["convergence_warnings"]) for c in candidates),
            "refit": sum(bool(r["refit_convergence_warnings"]) for r in result["folds"]),
            "position": sum(bool(r["position_convergence_warnings"]) for r in result["folds"]),
        }
        valid = [
            v["valid_replicates"]
            for target in summary["targets"].values()
            for method in target.values()
            for v in method.values()
        ]
        audit[name] = {
            "legacy_macro_auc": float(legacy_auc),
            "macro": macro,
            "grouped_minus_legacy_auc": float(macro["probe"]["auc"]["estimate"] - legacy_auc),
            "convergence_warning_fits": warnings,
            "total_fits": len(candidates) + 70,
            "minimum_valid_bootstrap_replicates": min(valid),
            "elapsed_seconds": result["execution"]["elapsed_seconds_this_invocation"],
            "fold_macro_auc": [
                float(
                    np.mean(
                        [r["metrics"]["probe"]["auc"] for r in result["folds"] if r["fold"] == f]
                    )
                )
                for f in range(5)
            ],
            "fold_sizes": [
                {
                    "fold": f["fold"],
                    "fit_responses": len(f["fit_responses"]),
                    "validation_responses": len(f["validation_responses"]),
                    "test_responses": len(f["test_responses"]),
                    "test_units": sum(u["response_id"] in f["test_responses"] for u in units),
                }
                for f in plan["folds"]
            ],
            "targets": summary["targets"],
        }
        runs[name] = result
    assert len(plan_hashes) == 1, "Models must share the exact split plan"
    table(
        OUT / "probe_grouped_summary_table.tex",
        "Response-grouped prospective probes on 38 responses and 3,087 units. AUROC is averaged equally across five outer folds and seven targets. Brackets are 95\\% response-bootstrap intervals (5,000 draws), conditional on saved folds, selected layers, and fits. The paired gain subtracts the prefix-position baseline. Legacy scores select layers by sentence-test accuracy, so the two protocols differ in both splitting and selection.",
        "tab:probe-grouped-summary",
        "lrrrr",
        "Model & Legacy AUROC & Grouped AUROC & Position AUROC & Paired gain",
        macro_rows,
    )
    table(
        OUT / "probe_grouped_targets_table.tex",
        "Response-grouped results by target. AUROC and the paired AUROC gain over the position baseline include 95\\% conditional response-bootstrap intervals. Balanced accuracy (BA) and binary F1 are mean-fold point estimates at the unchanged decision threshold; their intervals are retained in the result files. Indices list the validation-selected hidden states in outer-fold order, not a globally selected layer.",
        "tab:probe-grouped-targets",
        "llrrrrl",
        "Model & Target & AUROC & Gain over position & BA & F1 & Indices (folds 1--5)",
        target_rows,
    )
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    lower = min(
        r["summary"]["targets"][t][method]["auc"]["ci95"][0]
        for r in runs.values()
        for t in TARGETS
        for method in ("probe", "position")
    )
    lower = max(0.0, np.floor((lower - 0.02) * 10) / 10)
    fig, axes = plt.subplots(1, 3, figsize=(11.5, 4.4), sharey=True)
    for ax, (name, _) in zip(axes, MODELS):
        for method, offset, color, marker, label in [
            ("probe", -0.12, "#2563a4", "o", "Hidden-state probe"),
            ("position", 0.12, "#a96021", "s", "Prefix position"),
        ]:
            values = [runs[name]["summary"]["targets"][t][method]["auc"] for t in TARGETS]
            points = np.array([v["estimate"] for v in values])
            ci = np.array([v["ci95"] for v in values])
            y = np.arange(len(TARGETS)) + offset
            ax.hlines(y, ci[:, 0], ci[:, 1], color=color, linewidth=1.2)
            ax.plot(points, y, marker, color=color, label=label, markersize=4)
        ax.set_title(name)
        ax.set_yticks(range(len(TARGETS)), TARGETS)
        ax.set_xlim(lower, 1)
        ax.axvline(0.5, color="grey", ls=":", lw=1)
        ax.set_xlabel("Mean outer-fold AUROC")
        ax.grid(axis="x", alpha=0.2)
    axes[0].invert_yaxis()
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=2, frameon=False)
    fig.tight_layout(rect=[0, 0.09, 1, 1])
    for ext in ("pdf", "png"):
        path = OUT / "figures" / f"probe_grouped_auc.{ext}"
        fig.savefig(path, dpi=180, bbox_inches="tight")
    plt.close(fig)
    for path in [
        OUT / "probe_grouped_summary_table.tex",
        OUT / "probe_grouped_targets_table.tex",
        OUT / "figures/probe_grouped_auc.pdf",
        OUT / "figures/probe_grouped_auc.png",
    ]:
        hashes[str(path.relative_to(ROOT))] = digest(path)
    payload = {
        "schema_version": 1,
        "sha256": hashes,
        "split_plan_sha256": next(iter(plan_hashes)),
        "notes": [
            "Same response folds across all encoders and targets.",
            "No global layer selection from outer-test scores.",
            "Legacy/grouped differences change both splitting and layer-selection criterion.",
            "Bootstrap conditions on existing fits; no multiple-comparison adjustment.",
        ],
        "models": audit,
    }
    (OUT / "grouped_probe_sources.json").write_text(json.dumps(payload, indent=2) + "\n")
    for name, values in audit.items():
        print(name, json.dumps({k: v for k, v in values.items() if k not in ("targets", "macro")}))
        print(json.dumps(values["macro"], indent=2))


if __name__ == "__main__":
    main()
